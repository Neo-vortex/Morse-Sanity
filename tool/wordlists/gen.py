import re, sys
D = sys.argv[1] if len(sys.argv) > 1 else "tool/wordlists"
out = sys.argv[2] if len(sys.argv) > 2 else "lib/data/word_bank.dart"
basic = open(f'{D}/basic850.txt').read().split()
def words_in(name):
    lines = open(f'{D}/{name}').read().splitlines()
    return ' '.join(l for l in lines if not l.startswith('#')).split()

# Archaic or dialect words from 19th-century novels that sound odd on air.
ARCHAIC = set('''THOU THEE THY THINE HATH DOTH SHALT WILT NAY AYE YE ERE TIS TWAS
WHILST AMONGST UPON HITHER THITHER WHENCE NIGH OFT SAITH ART'''.split())

common = [w for w in words_in('common_words.txt') if w not in ARCHAIC]
radio = words_in('radio_words.txt') + words_in('radio_words_mined.txt')
fix = {'COLOUR': 'COLOR', 'BEHAVIOUR': 'BEHAVIOR', 'HUMOUR': 'HUMOR'}
basic = [fix.get(w, w) for w in basic]
def uniq(xs):
    seen = set(); r = []
    for x in xs:
        if x not in seen and re.fullmatch(r'[A-Z]+', x):
            seen.add(x); r.append(x)
    return r
basic = uniq(basic)
radio = uniq(radio)
common = uniq(common)
def dart_list(name, words, doc):
    lines = [f'/// {doc}', f'const List<String> {name} = [']
    row = '  '
    for w in words:
        item = f"'{w}', "
        if len(row) + len(item) > 80:
            lines.append(row.rstrip()); row = '  '
        row += item
    lines.append(row.rstrip())
    lines.append('];')
    return '\n'.join(lines)
src = f"""// Generated by tool/wordlists/gen.py from the lists next to it; edit those.
//
// basicEnglishWords: C. K. Ogden's Basic English core vocabulary (850 words,
// published 1930, public domain), as listed at
// https://en.wiktionary.org/wiki/Appendix:Basic_English_word_list
// with British spellings changed to American ones.
//
// commonWords: the most frequent everyday words in public-domain Project
// Gutenberg novels (see mine_gutenberg.py), most frequent first.
//
// radioWords: everyday amateur-radio vocabulary curated for this app, plus
// terms mined from public-domain radio and telegraph books.

{dart_list('basicEnglishWords', basic, "Ogden's Basic English core vocabulary.")}

{dart_list('commonWords', common, 'Frequency-ranked everyday English words.')}

{dart_list('radioWords', radio, 'Words heard in everyday amateur-radio contacts.')}
"""
open(out, 'w').write(src)
print(len(basic), 'basic;', len(common), 'common;', len(radio), 'radio')
